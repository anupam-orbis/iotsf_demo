#!/usr/bin/env python3
"""The paper's Moirai inference with the strict freeze (H) as the frozen arm, beside the frozen encoder (D).

WHY. Reviewer sq16: condition D leaves in_proj and mask_encoding trainable, so "freezing wins" under D
could be those modules adapting. Since the v58 runs, H exists on all 22 Moirai cells (the 21 matrix
cells plus ILI), so every Moirai statistic the body reports under F=D can be reported under F=H too.
Nothing new is computed here; the procedures are imported unchanged:
  per-cell call  paired_inference.t_interval + benjamini_hochberg + call_of, BH across the Moirai cells
                 that carry H (22), on paired per-seed B-H differences (same seeds, same denominator
                 as cell_matrix.strict_freeze_cells)
  association    clustered_inference.both: Spearman of B's CKA against the cell's mean contrast, with
                 the cell-level and (backbone, dataset)-cluster bootstrap intervals, n_boot 10000, seed 0
The B-D versions are recomputed by the same code on the same cells and asserted to reproduce the
published within-Moirai rho (+0.168, clustered [-0.469, +0.717]) before anything is printed for H.

Run:  python3 scripts/strict_freeze_inference.py     (writes results/strict_freeze_inference.json)
"""
import contextlib
import io
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import cell_matrix as cm  # noqa: E402
import cluster_keys as ck  # noqa: E402
import clustered_inference as ci  # noqa: E402
import paired_inference as pi  # noqa: E402

OUT = ROOT / "results/strict_freeze_inference.json"


def per_seed_bh():
    """Paired per-seed B-H and B-D on the seeds H ran, exactly as strict_freeze_cells() averages."""
    import glob
    refs = cm._zs_test_refs()
    out = {}
    for d in [f for dd in cm.STRICT_FREEZE_DIRS for f in sorted(glob.glob(str(ROOT / dd / "*")))]:
        name = Path(d).name
        if name == "ili":
            continue
        H = {json.load(open(f))["seed"]: json.load(open(f)) for f in glob.glob(d + "/condition_H/*.json")}
        B, zs_t = cm._b_arm_for(name, refs)
        D = cm._d_arm_for(name)
        seeds = sorted(set(B) & set(H) & set(D))
        if not (zs_t and seeds):
            continue
        out[name] = dict(seeds=seeds,
                         bh=[(B[s]["test_mse"] - H[s]["test_mse"]) / zs_t * 100 for s in seeds],
                         bd=[(B[s]["test_mse"] - D[s]["test_mse"]) / zs_t * 100 for s in seeds])
    H = {json.load(open(f))["seed"]: json.load(open(f))
         for f in glob.glob(str(ROOT / "results/v45_strict_freeze/ili/condition_H_seed*.json"))}
    B = {json.load(open(f))["seed"]: json.load(open(f))
         for f in glob.glob(str(ROOT / "results/v40_ili_heldout/condition_B_seed*.json"))}
    Di = {json.load(open(f))["seed"]: json.load(open(f))
          for f in glob.glob(str(ROOT / "results/v40_ili_heldout/condition_D_seed*.json"))}
    seeds = sorted(set(B) & set(H) & set(Di))
    agg = lambda r: r["aggregate"]["forgetting_pct_test"]  # noqa: E731
    out["ili"] = dict(seeds=seeds, bh=[agg(B[s]) - agg(H[s]) for s in seeds],
                      bd=[agg(B[s]) - agg(Di[s]) for s in seeds])
    return out


def calls(ps, key):
    names = sorted(ps)
    tis = {n: pi.t_interval(ps[n][key]) for n in names}
    qs = pi.benjamini_hochberg([tis[n][2] for n in names])
    res = {}
    for n, q in zip(names, qs):
        lo, hi, p = tis[n]
        s = dict(mean=st.mean(ps[n][key]), lo=lo, hi=hi, p=p, q=q, n=len(ps[n][key]))
        s["call"] = pi.call_of(s)
        res[n] = s
    return res


def emit_tex(res, path=ROOT / "paper_8/tables/strictfreeze_calls.tex"):
    """Section 5's summary: the calls and the CKA association under each frozen arm, same 22 cells."""
    def row(label, calls, rho):
        lo, hi = rho["cluster_ci"]
        return (f"{label} & {calls['freeze']} & {calls['adapt']} & {calls['inconclusive']} & "
                f"${rho['rho']:+.3f}$ & $[{lo:+.3f}, {hi:+.3f}]$ \\\\")
    L = ["% GENERATED by scripts/strict_freeze_inference.py -- do not edit by hand.",
         "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
         "Frozen arm & Freeze better & Adapt better & Inconclusive & "
         "$\\rho$(CKA, $\\denc$) & 95\\% CI \\\\", "\\midrule",
         row("D (input projection trains)", res["calls_D_same_cells"], res["rho_D"]),
         row("H (strict: head only)", res["calls_H"], res["rho_H"]),
         "\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(L) + "\n")


def main():
    ps = per_seed_bh()
    assert len(ps) == 22, len(ps)
    sf = cm.strict_freeze_cells()
    for n, v in ps.items():  # the per-seed lists must reproduce the published means
        assert abs(st.mean(v["bh"]) - sf[n]["bh_test"]) < 1e-9, n

    with contextlib.redirect_stdout(io.StringIO()):
        rows = ci.rows()
    moirai = [r for r in rows if ck.backbone_of(r["cell"]) == "Moirai" and r.get("cka") is not None]
    cells = [r["cell"] for r in moirai]
    x = [r["cka"] for r in moirai]
    rho_d = ci.both(x, [r["bd_test"] for r in moirai], cells, 10000, 0)
    assert round(rho_d["rho"], 3) == 0.168 and [round(v, 3) for v in rho_d["cluster_ci"]] == [-0.469, 0.717], rho_d
    have_h = [r.get("bh_test") is not None for r in moirai]
    assert all(have_h), [c for c, h in zip(cells, have_h) if not h]
    rho_h = ci.both(x, [r["bh_test"] for r in moirai], cells, 10000, 0)

    ch, cd = calls(ps, "bh"), calls(ps, "bd")
    count = lambda c: {k: sum(v["call"] == k for v in c.values()) for k in ("freeze", "adapt", "inconclusive")}  # noqa: E731
    flips = sorted(n for n in ps if (st.mean(ps[n]["bh"]) > 0) != (st.mean(ps[n]["bd"]) > 0))
    res = dict(n_cells=len(ps), sign_disagreements=flips,
               calls_H=count(ch), calls_D_same_cells=count(cd),
               decisive_H={n: v for n, v in ch.items() if v["call"] != "inconclusive"},
               rho_D=rho_d, rho_H=rho_h, per_cell_H=ch)
    OUT.write_text(json.dumps(res, indent=1, default=float))
    emit_tex(res)

    print(f"Moirai cells with H: {len(ps)}; B-H and B-D disagree in sign on {len(flips)}: {flips}")
    print(f"calls, F=H (BH over {len(ps)}): {res['calls_H']}")
    print(f"calls, F=D on the same cells and seeds: {res['calls_D_same_cells']}")
    for n, v in sorted(res["decisive_H"].items()):
        print(f"   {n:26s} {v['call']:7s} mean {v['mean']:+6.1f}  95% [{v['lo']:+.1f}, {v['hi']:+.1f}]  "
              f"q {v['q']:.3f}  n {v['n']}")
    for lab, r in (("D", rho_d), ("H", rho_h)):
        print(f"within-Moirai rho(CKA, B-{lab}) {r['rho']:+.3f}  cells {r['n']}  "
              f"clustered [{r['cluster_ci'][0]:+.3f}, {r['cluster_ci'][1]:+.3f}] ({r['n_clusters']} clusters)  "
              f"cell-level [{r['cell_ci'][0]:+.3f}, {r['cell_ci'][1]:+.3f}]")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
