#!/usr/bin/env python3
"""Emit paper_8/tables/layerunfreeze.tex from the run records.

The layer-wise unfreeze ladder on Moirai-Small/ETTh2, h=96, n=10,000: N is the number of top
transformer layers left trainable (Moirai-Small has 6), so N=0 is condition D and N=6 is condition B.

WHY HELD-OUT FIRST. The previous hand-typed table read the ladder on the trainer's
forgetting_pct, which is scored on the selection windows the early-stopping rule also chose the
epoch on. On those windows the matched pair N=3 / N=6 looked indistinguishable (-5.9 vs -7.9). Scored
against the held-out zero-shot reference -- the outcome the paper reads everywhere else -- the ladder
is monotone in N and the pair is separated by about four standard errors. Both readings are printed,
held-out as the outcome and selection as contrast, the same layout as tables/sample_sweep.tex.

Dispersion is the standard error of the mean over seeds, the body's convention.

Run:  /opt/homebrew/bin/python3 scripts/emit_layerunfreeze.py
"""
import glob
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "paper_8/tables/layerunfreeze.tex"
sys.path.insert(0, str(ROOT / "scripts"))
from cell_matrix import _zs_test_refs  # noqa: E402

# Rows listed explicitly so a new result directory cannot silently join one. N=0 is the older
# final-epoch condition-D record (no early stopping); N=3..6 share one root, protocol and environment
# (MPS, early-stopped, best state restored). N=1 diverged (NaN at epoch 11) and left no record.
ROWS = [
    (0, "results/v18_cond_d_probe/seed*/condition_D_h96_s*.json", "final"),
    (3, "results/v49_layerunfreeze_10seed/N3_seed*/*.json", "best"),
    (4, "results/v49_layerunfreeze_10seed/N4_seed*/*.json", "best"),
    (5, "results/v49_layerunfreeze_10seed/N5_seed*/*.json", "best"),
    (6, "results/v49_layerunfreeze_10seed/N6_seed*/*.json", "best"),
]


def load(pattern, zs_test):
    rows = []
    for f in sorted(glob.glob(str(ROOT / pattern))):
        j = json.loads(Path(f).read_text())
        assert j["horizon"] == 96 and j["model_size"] == "small", f
        j["heldout_forgetting_pct"] = (j["test_mse"] - zs_test) / zs_test * 100
        rows.append(j)
    assert rows, pattern
    return rows


def ms(rows, key, nd):
    v = [r[key] for r in rows]
    sem = st.stdev(v) / len(v) ** 0.5
    return f"${st.mean(v):.{nd}f}{{\\pm}}{sem:.{nd}f}$"


def pct(rows, key):
    v = [r[key] for r in rows]
    return f"{ms(rows, key, 1)} ({sum(x < 0 for x in v)}/{len(v)})"


def ladder():
    zs_test = _zs_test_refs()["small_ETTh2_h96"]
    return [(n, load(p, zs_test), stop) for n, p, stop in ROWS]


def main():
    data = ladder()
    L = ["% GENERATED by scripts/emit_layerunfreeze.py -- do not edit by hand.",
         "\\begin{table}[ht]", "\\centering",
         "\\caption{Layer-wise unfreeze ladder on Moirai-Small/ETTh2 ($h{=}96$, $n{=}10$k).",
         "$N$ is the number of top transformer layers left trainable, so $N{=}0$ is condition~D",
         "and $N{=}6$ is condition~B.  Held-out forgetting is against the held-out zero-shot MSE",
         "and is the outcome; selection-window forgetting is shown for contrast.  Mean${\\pm}$SEM",
         "over seeds, with the count of seeds improving on zero-shot.  $N{=}3$--$6$ share one",
         "root, protocol and environment and restore the best selection-window epoch;",
         "$N{=}0$ is an older record read at the final epoch.  $N{=}1$ diverged (NaN at epoch",
         "11) and is omitted.}",
         "\\label{tab:layerunfreeze}", "\\small",
         "\\begin{tabular}{@{}rccccc@{}}", "\\toprule",
         "$N$ & $k$ & CKA & $\\ell_2$ drift & Forg.\\% (held-out) & Forg.\\% (sel.) \\\\",
         "\\midrule"]
    for n, rows, stop in data:
        mark = "$^{\\dagger}$" if stop == "final" else ""
        L.append(f"{n}{mark} & {len(rows)} & {ms(rows, 'final_cka', 3)} & "
                 f"{ms(rows, 'final_weight_drift', 2)} & {pct(rows, 'heldout_forgetting_pct')} & "
                 f"{pct(rows, 'forgetting_pct')} \\\\")
    # The N=4/N=5 top-up registration (preregistration_ladder.json) fixed selection-window
    # forgetting_pct with population std (ddof=0) as its statistic; print that form verbatim so the
    # registered reading is on the page beside the post-hoc held-out one.
    regd = "; ".join(
        f"$N{{=}}{n}$: ${st.mean(r['forgetting_pct'] for r in rows):.1f}"
        f"{{\\pm}}{st.pstdev([r['forgetting_pct'] for r in rows]):.1f}$"
        for n, rows, _ in data if n in (4, 5))
    L += ["\\bottomrule", "\\end{tabular}", "", "\\smallskip",
          "{\\footnotesize $^{\\dagger}$Final epoch, no early stopping.  The registered statistic",
          f"for the $N{{=}}4,5$ top-up is selection-window forgetting, mean${{\\pm}}$population std: {regd}.",
          "The held-out column is a post-hoc reading.  Rows read",
          "\\texttt{test\\_mse}, \\texttt{forgetting\\_pct}, \\texttt{final\\_cka} and",
          "\\texttt{final\\_weight\\_drift} from \\texttt{results/v49\\_layerunfreeze\\_10seed} and",
          "\\texttt{results/v18\\_cond\\_d\\_probe}.}",
          "\\end{table}"]
    OUT.write_text("\n".join(L) + "\n")

    print("LAYER-WISE UNFREEZE LADDER, from the run records")
    for n, rows, _ in data:
        h = [r["heldout_forgetting_pct"] for r in rows]
        print(f"  N={n}: k={len(rows)} cka={st.mean(r['final_cka'] for r in rows):.3f} "
              f"held={st.mean(h):+.1f} sem={st.stdev(h) / len(h) ** .5:.1f}")
    a = [r["heldout_forgetting_pct"] for r in data[1][1]]
    b = [r["heldout_forgetting_pct"] for r in data[4][1]]
    se = (st.variance(a) / len(a) + st.variance(b) / len(b)) ** 0.5
    print(f"  N=3 minus N=6 held-out: {st.mean(a) - st.mean(b):+.1f} on SE {se:.1f} "
          f"({(st.mean(a) - st.mean(b)) / se:.1f} SE)")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
